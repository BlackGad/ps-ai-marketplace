$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot -Parent
# The integration sequence with fakes: install the defaults, set up accounts, add and remove ci-extra, then uninstall everything.
. (Join-Path $PSScriptRoot 'fixtures/install/UninstallSandbox.ps1')
$savedPath = $env:PATH
try {
    # Account ids must not already be commands; keep the machine PATH out of the fake setup.
    $env:PATH = Split-Path (Get-Process -Id $PID).Path
    . (Join-Path $repo 'plugins/legion/bin/legion-setup.ps1') -NoRun
    $bin = Join-Path $sandbox '.legion/bin'
    New-Item -ItemType Directory -Path $bin -Force | Out-Null
    $commandNames = if ($IsWindows) { @('legion', 'legion.cmd') } else { @('legion') }
    $plugin = New-InstallFixturePlugin -Path (Join-Path $sandbox 'plugin')
    New-Item -ItemType File -Path (Join-Path $plugin 'bin/legion-refresh.ps1') -Force | Out-Null
    # Owner key -> what the fake CLI has installed in that folder.
    $installed = @{}
    $uninstalled = [Collections.Generic.List[string]]::new()
    function Invoke-ClosedInput {
        param([string[]]$Command, $Environment)
        if ($Command -contains '-File') {
            foreach ($name in $commandNames) { [IO.File]::WriteAllText((Join-Path $bin $name), "# Generated by legion: owner command`n") }
            return @{ ExitCode = 0; Output = @(); ErrorOutput = @() }
        }
        $tool = $catalog.tools | Where-Object command -CEQ $Command[0]
        $owner = Get-LegionTargetOwner -Tool $tool -Folder $Environment[$tool.configEnv] -HomeRoot $sandbox
        $target = $installed[$owner]
        $line = @($Command | Select-Object -Skip 1) -join '|'
        if ($line -ceq ($tool.plugin.list -join '|')) {
            $output = if ($tool.plugin.listing.format -eq 'json') {
                if ($target.Plugin) { '[{"id":"legion@ps-legion-marketplace","enabled":true}]' } else { '[]' }
            } elseif ($target.Plugin) { 'legion@ps-legion-marketplace installed' } else { '' }
        } elseif ($line -ceq ($tool.plugin.marketplaceList -join '|')) {
            $output = Get-FixtureMarketplaceListing -Tool $tool.id -Source $(if ($target.Marketplace) { 'example/marketplace' } else { '' })
        } elseif ($line -ceq ($tool.plugin.uninstall -join '|')) {
            $target.Plugin = $false
            $uninstalled.Add($owner)
            $output = ''
        } elseif ($line -ceq ($tool.plugin.marketplaceRemove -join '|')) {
            $target.Marketplace = $false
            $output = ''
        } else { throw "Unexpected fake command: $line" }
        return @{ ExitCode = 0; Output = @($output); ErrorOutput = @() }
    }
    # What the installer does for one target: the CLI installs legion, then the refresh records and writes the command.
    function Install-FixtureTarget {
        param($Tool, [string]$Folder)
        $installed[(Get-LegionTargetOwner -Tool $Tool -Folder $Folder -HomeRoot $sandbox)] = @{ Plugin = $true; Marketplace = $true }
        $null = Invoke-InstallRefresh -Entry $Tool -ConfigDir $Folder -PluginRoot $plugin
    }

    foreach ($tool in $catalog.tools) {
        $explicit = (Resolve-InstallConfigDir $tool.plugin.defaultConfigDir) + [IO.Path]::DirectorySeparatorChar
        if ($IsWindows) { $explicit = $explicit.ToUpperInvariant() }
        Assert-Equal (Get-LegionTargetOwner -Tool $tool -HomeRoot $sandbox) (Get-LegionTargetOwner -Tool $tool -Folder $explicit -HomeRoot $sandbox) 'Default and explicit folders share one owner key'
        Install-FixtureTarget -Tool $tool
    }
    $accounts = [ordered]@{ claude1 = 'claude'; codex1 = 'codex'; copilot1 = 'copilot'; 'ci-extra' = 'claude' }
    foreach ($id in $accounts.Keys) {
        $null = & (Join-Path $repo 'plugins/legion/bin/legion-account.ps1') -Action add -Id $id -Tool $accounts[$id] -Command (Get-Process -Id $PID).Path -HomeRoot $sandbox
        $folder = Join-Path $sandbox ".legion/agents/$id"
        Install-FixtureTarget -Tool ($catalog.tools | Where-Object id -CEQ $accounts[$id]) -Folder $folder
        $null = Add-SetupAllowRules -Plan @{ HomeRoot = $sandbox; Accounts = @(@{ Usable = $true; Tool = (Get-LegionTool -Tool $accounts[$id]); Folder = $folder }) }
    }
    $edits = @(Get-LegionFootprints -HomeRoot $sandbox -Kind edit)
    Assert-Equal 'claude|claude' (@($edits | ForEach-Object { ($_.owners -split ':')[0] }) -join '|') 'Only Claude targets record the allow rule; Codex and Copilot declare none'
    foreach ($id in 'codex1', 'copilot1') { Assert-Equal $false (Test-Path (Join-Path $sandbox ".legion/agents/$id/settings.json")) "No Claude settings are written for $id" }

    $extra = Join-Path $sandbox '.legion/agents/ci-extra'
    $null = & (Join-Path $repo 'plugins/legion/bin/legion-account.ps1') -Action remove -Id ci-extra -HomeRoot $sandbox
    Assert-True (Test-Path (Join-Path $extra 'settings.json')) 'Account removal keeps the folder and its settings'

    $null = Invoke-LegionInstaller -Catalog $catalog -Uninstall -Yes
    foreach ($name in $commandNames) { Assert-Equal $false (Test-Path (Join-Path $bin $name)) "Owner command $name goes with its last target" }
    $extraOwner = Get-LegionTargetOwner -Tool $catalog.tools[0] -Folder $extra -HomeRoot $sandbox
    Assert-True ($uninstalled -ccontains $extraOwner) 'Uninstall reaches the recorded target of a removed account'
    Assert-Equal 7 $uninstalled.Count 'Uninstall reaches the defaults and the four account folders once each'
    Assert-Equal 0 @(Get-LegionFootprints -HomeRoot $sandbox | Where-Object { $_.kind -cin 'file', 'edit' }).Count 'No target-owned footprints remain'
    Assert-Equal $false ([IO.File]::ReadAllText((Join-Path $extra 'settings.json')).Contains('LEGION_ROLE')) 'The removed account allow rule is undone'
    foreach ($id in 'claude1', 'codex1', 'copilot1') { Assert-True (Test-Path (Join-Path $bin $id)) "Launcher $id stays" }
    $repeat = @(Invoke-LegionInstaller -Catalog $catalog -Uninstall -Yes) -join "`n"
    Assert-True ($repeat.Contains('Nothing to uninstall.')) 'A repeat uninstall changes nothing'
} finally { $env:PATH = $savedPath; Remove-UninstallSandbox }
