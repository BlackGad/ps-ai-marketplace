$repo = Split-Path $PSScriptRoot -Parent
& {
    . (Join-Path $PSScriptRoot 'fixtures/install/UninstallSandbox.ps1')
    try {
        $bin = Join-Path $sandbox '.legion/bin'
        New-Item -ItemType Directory -Path $bin -Force | Out-Null
        $commands = [ordered]@{ 'legion' = 'legion.ps1'; 'ps-ai-setup' = 'ps-ai-setup.ps1'; 'ps-ai-status' = 'ps-ai-status.ps1' }
        foreach ($name in $commands.Keys) {
            "#!/bin/sh`nexec pwsh -NoProfile -File '/plugin/bin/$($commands[$name])' `"`$@`"" | Set-Content (Join-Path $bin $name)
            "@pwsh -NoProfile -File `"C:\plugin\bin\$($commands[$name])`" %*" | Set-Content (Join-Path $bin "$name.cmd")
        }
        # Another program's file with a ps-ai name, an account wrapper and an unrelated file stay.
        'owner file' | Set-Content (Join-Path $bin 'other-legion')
        "#!/bin/sh`n# Generated by ps-ai: account codex-a`nexit 0" | Set-Content (Join-Path $bin 'codex-a')
        'unrelated' | Set-Content (Join-Path $bin 'unrelated')
        $owner = [pscustomobject]@{ agents = @() }

        $files = @(Get-UninstallFiles -Owner $owner)
        foreach ($name in $commands.Keys) {
            Assert-True ($files -contains (Join-Path $bin $name)) "$name is planned for removal"
            Assert-True ($files -contains (Join-Path $bin "$name.cmd")) "$name.cmd is planned for removal"
        }

        $preview = @(Invoke-PsAiInstaller -Catalog $catalog -Uninstall -DryRun) -join "`n"
        foreach ($name in $commands.Keys) {
            Assert-True ($preview.Contains((Join-Path $bin $name))) "The uninstall plan lists $name"
        }

        $null = Invoke-PsAiInstaller -Catalog $catalog -Uninstall -Yes
        foreach ($name in $commands.Keys) {
            Assert-True (-not (Test-Path (Join-Path $bin $name))) "$name removed"
            Assert-True (-not (Test-Path (Join-Path $bin "$name.cmd"))) "$name.cmd removed"
        }
        foreach ($name in @('other-legion', 'codex-a', 'unrelated')) {
            Assert-True (Test-Path (Join-Path $bin $name)) "$name kept"
        }

        # A different file with a command name is left alone.
        foreach ($name in $commands.Keys) { 'someone else' | Set-Content (Join-Path $bin $name) }
        $files = @(Get-UninstallFiles -Owner $owner)
        foreach ($name in $commands.Keys) {
            Assert-True ($files -notcontains (Join-Path $bin $name)) "A foreign $name is not planned"
        }
        $null = Invoke-PsAiInstaller -Catalog $catalog -Uninstall -Yes
        foreach ($name in $commands.Keys) { Assert-True (Test-Path (Join-Path $bin $name)) "A foreign $name is kept" }
    } finally { Remove-UninstallSandbox }
}
