$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path $PSScriptRoot -Parent
$pattern = '(?i)ps' + '-ai|ps' + '_ai|ps' + 'ai'
# D1/D2 compatibility is intentionally unchanged by the plugin rename. Limit
# exceptions to those existing definitions and the fixtures that exercise them.
$oldProduct = 'ps' + '-ai'
$oldRole = 'PS' + '_AI'
$retiredCommands = $oldProduct + '-(?:setup|status|overseer)'
$ownerFiles = $oldProduct + '-(?:personalisation\.json|notes\.md|update\.json|install-)|\.' + $oldProduct + '-runtime'
$launcherHeader = 'Generated by ' + $oldProduct
$oldRepositorySyntax = $oldRole + '|' + $oldProduct + '(?=\|legion| orchestration| plugin| personalisation|/schemas/)'
$allowances = @{
    'plugins/legion/bin/lib/commands.ps1' = @($retiredCommands)
    'plugins/legion/bin/lib/paths.ps1' = @($ownerFiles)
    'plugins/legion/install.ps1' = @($ownerFiles, $launcherHeader, ('bin/' + $oldProduct + '-foundry\.ps1'), ('(?<=foreach \(\$prefix in @\(''legion'', '')' + $oldProduct + '(?=''\)\))'))
    'plugins/legion/bin/legion-account.ps1' = @($launcherHeader, ("(?<=')" + $oldProduct + "-(?=')"))
    'plugins/legion/bin/legion-refresh.ps1' = @($launcherHeader)
    'plugins/legion/bin/legion-setup.ps1' = @($launcherHeader)
    'plugins/legion/skills/legion-codex/scripts/foundry-config.ps1' = @($oldProduct + '-foundry')
    'plugins/legion/bin/legion-repository.ps1' = @($oldRepositorySyntax)
    'plugins/legion/skills/legion-repository/references/migrate.md' = @($oldRepositorySyntax)
    'tests/OwnerFileMigration.Tests.ps1' = @($oldProduct, $oldRole)
    'tests/RetiredCommands.Tests.ps1' = @($retiredCommands, ('(?<=\^)' + $oldProduct + '-'))
    'tests/Account.Tests.ps1' = @($retiredCommands, $launcherHeader)
    'tests/Commands.Tests.ps1' = @($retiredCommands)
    'tests/DetectMode.Tests.ps1' = @($oldRole)
    'tests/UpdateHook.Tests.ps1' = @($oldRole)
    'tests/InstallOwnerCommands.Tests.ps1' = @($retiredCommands)
    'tests/InstallUninstall.Tests.ps1' = @($ownerFiles, $launcherHeader)
    'tests/InstallUninstallCommands.Tests.ps1' = @($launcherHeader)
    'tests/InstallUninstallRepair.Tests.ps1' = @($launcherHeader)
    'tests/InstallUninstallPurge.Tests.ps1' = @($ownerFiles)
    'tests/Refresh.Tests.ps1' = @($retiredCommands, $launcherHeader)
    'tests/Setup.Tests.ps1' = @($retiredCommands)
}
$files = @(git -C $repoRoot ls-files)
if ($LASTEXITCODE -ne 0 -or -not $files.Count) { throw 'Could not list tracked files' }
$violations = @(
    foreach ($file in $files) {
        if ($file -eq 'CHANGELOG.md' -or -not (Test-Path -LiteralPath (Join-Path $repoRoot $file) -PathType Leaf)) { continue }
        $text = [IO.File]::ReadAllText((Join-Path $repoRoot $file))
        $text = $text.Replace(('BlackGad/ps' + '-ai-marketplace'), 'repository-address')
        foreach ($allowance in $allowances[$file]) { $text = [regex]::Replace($text, $allowance, '') }
        if ($text -match $pattern -or $file -match $pattern) { $file }
    }
)
if ($violations.Count) { throw "Legacy names remain in $($violations.Count) tracked files: $($violations -join ', ')" }
