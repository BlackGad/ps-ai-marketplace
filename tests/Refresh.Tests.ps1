$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$refresh = Join-Path $root 'plugins/ps-ai/bin/ps-ai-refresh.ps1'
$tempRoot = Join-Path $root ('.agents/temp/refresh-' + [guid]::NewGuid())
New-Item -ItemType Directory -Path $tempRoot -Force | Out-Null
try {
    # RefreshCreatesMissing / RefreshAlternateHome: an empty alternate home needs usable commands.
    $alternateHome = Join-Path $tempRoot 'alternate home'
    & $refresh -HomeRoot $alternateHome | Out-Null
    & {
        . (Join-Path $root 'plugins/ps-ai/bin/ps-ai-account.ps1') -NoRun
        foreach ($name in @('legion')) {
            $path = Join-Path $alternateHome ".legion/bin/$name"
            Assert-True (Test-Path -LiteralPath $path -PathType Leaf) "RefreshCreatesMissing creates $name"
            Assert-True (Test-LegionLauncherExecutable -Path $path) "RefreshCreatesMissing makes $name executable"
            Assert-Equal $IsWindows (Test-Path -LiteralPath "$path.cmd") 'RefreshCreatesMissing creates missing batch shims only on Windows'
            $suffixes = if ($IsWindows) { @('', '.cmd') } else { @('') }
            foreach ($suffix in $suffixes) {
                $target = Read-LegionOwnerCommandTarget -Path "$path$suffix" -Script "$name.ps1"
                Assert-Equal (Join-Path $root "plugins/ps-ai/bin/$name.ps1") $target.Path 'RefreshCreatesMissing targets the installed script'
                Assert-Equal 1 (@($target.Arguments | Where-Object { $_ -eq '-HomeRoot' }).Count) 'RefreshAlternateHome binds the new shim once'
                Assert-Equal $alternateHome ($target.Arguments[1].Trim("'" + '"')) 'RefreshAlternateHome binds the selected home'
            }
        }
    }
    $alternateBin = Join-Path $alternateHome '.legion/bin'
    $beforeMissing = @(Get-ChildItem $alternateBin -File | Sort-Object Name | ForEach-Object { $_.LastWriteTimeUtc.Ticks }) -join '|'
    $repeatMissing = @(& $refresh -HomeRoot $alternateHome)
    Assert-True ([bool]($repeatMissing -match '^skip: .*\(already done\)$')) 'RefreshCreatesMissing reports skip on the second run'
    Assert-Equal $beforeMissing (@(Get-ChildItem $alternateBin -File | Sort-Object Name | ForEach-Object { $_.LastWriteTimeUtc.Ticks }) -join '|') 'RefreshCreatesMissing writes nothing on the second run'

    # RefreshKeepsBlocked: a foreign command stays even while missing siblings are created.
    $blockedHome = Join-Path $tempRoot 'blocked home'
    $blockedBin = Join-Path $blockedHome '.legion/bin'
    New-Item -ItemType Directory -Path $blockedBin -Force | Out-Null
    foreach ($suffix in @('', '.cmd')) {
        [IO.File]::WriteAllText((Join-Path $blockedBin "legion$suffix"), 'foreign command')
    }
    & $refresh -HomeRoot $blockedHome | Out-Null
    foreach ($suffix in @('', '.cmd')) {
        Assert-Equal 'foreign command' ([IO.File]::ReadAllText((Join-Path $blockedBin "legion$suffix"))) 'RefreshKeepsBlocked preserves foreign command bytes'
    }
    Assert-True (-not (Test-Path -LiteralPath (Join-Path $blockedBin 'ps-ai-status'))) 'RefreshKeepsBlocked writes no old commands'

    $config = Join-Path $tempRoot '.legion/configuration'
    $bin = Join-Path $tempRoot '.legion/bin'
    $runtime = Join-Path $bin '.ps-ai-runtime/bin'
    New-Item -ItemType Directory -Path $config, $runtime -Force | Out-Null
    $file = Join-Path $config 'ps-ai-personalisation.json'
    @{
        agents=@(
            @{id='foundry-a';tool='claude';command=$(if ($IsWindows) { '~/.legion/bin/foundry-a.cmd' } else { '~/.legion/bin/foundry-a' });configDir='~/.legion/agents/foundry-a';provider=@{kind='foundry'}},
            @{id='external';tool='claude';command='~/custom/external';provider=@{kind='foundry'}}
        )
        projects=@{example=@{custom='keep'}}
    } | ConvertTo-Json -Depth 20 | Set-Content $file
    $ownerBytes = [IO.File]::ReadAllText($file)
    & {
        . (Join-Path $root 'plugins/ps-ai/bin/ps-ai-account.ps1') -NoRun
        New-FoundryWrappers -Id foundry-a -Tool claude -HomeRoot $tempRoot
    }
    'stale runtime' | Set-Content (Join-Path $runtime 'ps-ai-foundry.ps1')
    foreach ($name in @('foundry', 'tools')) {
        'stale library' | Set-Content (Join-Path $runtime "lib/$name.ps1")
    }
    "#!/bin/sh`n# Generated by ps-ai: account foundry-a`nstale wrapper" | Set-Content (Join-Path $bin 'foundry-a')
    'custom wrapper' | Set-Content (Join-Path $bin 'external')
    $shim = Join-Path $bin 'legion'
    @'
#!/bin/sh
exec pwsh -NoProfile -File '/old/owner'"'"'s/cache/bin/legion.ps1' -Account chosen "$@"
'@ | Set-Content $shim
    $cmdShim = Join-Path $bin 'legion.cmd'
    '@pwsh -NoProfile -File "C:\old\cache\bin\legion.ps1" -Account chosen -Repo "\\server\team$\work folder" %*' | Set-Content $cmdShim
    & $refresh -HomeRoot $tempRoot | Out-Null
    $homeFlag = & {
        . (Join-Path $root 'plugins/ps-ai/bin/ps-ai-account.ps1') -NoRun
        '-HomeRoot ' + (ConvertTo-LegionShellLiteral $tempRoot)
    }
    Assert-True ((Get-Content $shim -Raw).Contains($homeFlag)) 'R4 B4 refresh binds an older unbound command to the selected home'
    & $refresh -HomeRoot $tempRoot | Out-Null
    Assert-Equal 1 ([regex]::Matches((Get-Content $shim -Raw), '-HomeRoot ').Count) 'R4 B4 refresh preserves one home binding'
    & $refresh -HomeRoot $tempRoot | Out-Null
    Assert-Equal ([IO.File]::ReadAllText((Join-Path $root 'plugins/ps-ai/bin/ps-ai-foundry.ps1'))) ([IO.File]::ReadAllText((Join-Path $runtime 'ps-ai-foundry.ps1'))) 'Approved refresh updates copied runtime bytes'
    foreach ($name in @('foundry', 'tools')) {
        Assert-Equal ([IO.File]::ReadAllText((Join-Path $root "plugins/ps-ai/bin/lib/$name.ps1"))) ([IO.File]::ReadAllText((Join-Path $runtime "lib/$name.ps1"))) "Refresh updates the $name library in the current runtime layout"
    }
    & {
        . (Join-Path $runtime 'ps-ai-foundry.ps1') -NoRun
        Assert-Equal 'claude' (@(Get-LegionTools).id -join '|') 'Refreshed runner loads libraries and discovers its copied skill with the copied schema'
    }
    Assert-True ((Get-Content (Join-Path $bin 'foundry-a') -Raw).Contains('.ps-ai-runtime')) 'Refresh regenerates owned Foundry wrapper'
    foreach ($path in @($shim,$cmdShim)) {
        $text = Get-Content $path -Raw
        Assert-True ($text.Contains((Join-Path $root 'plugins/ps-ai/bin/legion.ps1'))) 'Refresh retargets the existing legion shim'
        Assert-True ($text.Contains('-Account chosen')) 'Refresh preserves shim arguments'
    }
    Assert-True ((Get-Content $cmdShim -Raw).Contains('-Repo "\\server\team$\work folder"')) 'R5 B2 refresh preserves the quoted batch dollar path'
    Assert-Equal $ownerBytes ([IO.File]::ReadAllText($file)) 'Refresh preserves owner settings bytes'
    Assert-Equal 'custom wrapper' (Get-Content (Join-Path $bin 'external')) 'External command remains untouched'
    [IO.File]::WriteAllText((Join-Path $bin 'legion'), 'unrelated owner command')
    & $refresh -HomeRoot $tempRoot | Out-Null
    Assert-Equal 'unrelated owner command' ([IO.File]::ReadAllText((Join-Path $bin 'legion'))) 'Refresh leaves an unrelated command untouched'
    $before = @(Get-ChildItem $bin -File -Recurse | Sort-Object FullName | ForEach-Object { $_.LastWriteTimeUtc.Ticks }) -join '|'
    $repeat = @(& $refresh -HomeRoot $tempRoot)
    Assert-True ([bool]($repeat -match '^skip: .*\(already done\)$')) 'Repeated refresh reports skip'
    Assert-Equal $before (@(Get-ChildItem $bin -File -Recurse | Sort-Object FullName | ForEach-Object { $_.LastWriteTimeUtc.Ticks }) -join '|') 'Repeated refresh writes nothing'
    # C-1: a file that only mentions the launcher in a comment or a later argument is not rewritten.
    $lookalike = "#!/bin/sh`n# pwsh -NoProfile -File '/old/cache/bin/legion.ps1'`necho mine"
    [IO.File]::WriteAllText((Join-Path $bin 'legion'), $lookalike)
    $argumentOnly = "#!/bin/sh`nexec pwsh -NoProfile -File /mine/tool.ps1 '/old/cache/bin/ps-ai-status.ps1'`n"
    [IO.File]::WriteAllText((Join-Path $bin 'ps-ai-status'), $argumentOnly)
    & $refresh -HomeRoot $tempRoot | Out-Null
    Assert-Equal $lookalike ([IO.File]::ReadAllText((Join-Path $bin 'legion'))) 'Refresh leaves a comment-only mention untouched'
    Assert-Equal $argumentOnly ([IO.File]::ReadAllText((Join-Path $bin 'ps-ai-status'))) 'Refresh leaves a later-argument mention untouched'
    # C-2: an owned command whose script is gone is rewritten to the current one.
    $stale = "#!/bin/sh`nexec pwsh -NoProfile -File '/gone/cache/bin/legion.ps1' -OwnerFlag keep `"`$@`"`n"
    [IO.File]::WriteAllText((Join-Path $bin 'legion'), $stale)
    & $refresh -HomeRoot $tempRoot | Out-Null
    $fixed = [IO.File]::ReadAllText((Join-Path $bin 'legion'))
    Assert-True ($fixed.Contains((Join-Path $root 'plugins/ps-ai/bin/legion.ps1')) -and $fixed.Contains('-OwnerFlag keep')) 'Refresh retargets a stale command and keeps its flags'
} finally {
    if ([IO.Path]::GetFullPath($tempRoot).StartsWith([IO.Path]::GetFullPath((Join-Path $root '.agents/temp/')))) {
        Remove-Item -LiteralPath $tempRoot -Recurse -Force
    }
}
