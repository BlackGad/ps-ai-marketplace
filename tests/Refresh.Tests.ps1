$ErrorActionPreference = 'Stop'
# Refresh syncs the legion app through the fake uv.
$env:LEGION_TEST_UV_SYNC = '1'
$root = Split-Path $PSScriptRoot -Parent
$refresh = Join-Path $root 'plugins/legion/bin/legion-refresh.ps1'
$version = (Get-Content -LiteralPath (Join-Path $root 'plugins/legion/plugin.json') -Raw | ConvertFrom-Json).version
$tempRoot = Join-Path $root ('.agents/temp/refresh-' + [guid]::NewGuid())
New-Item -ItemType Directory -Path $tempRoot -Force | Out-Null
try {
    # RefreshCreatesMissing / RefreshAlternateHome: an empty alternate home needs usable commands.
    $alternateHome = Join-Path $tempRoot 'alternate home'
    & $refresh -HomeRoot $alternateHome | Out-Null
    & {
        . (Join-Path $root 'plugins/legion/bin/lib/accounts.ps1')
        foreach ($name in @('legion')) {
            $path = Join-Path $alternateHome ".legion/bin/$name"
            Assert-True (Test-Path -LiteralPath $path -PathType Leaf) "RefreshCreatesMissing creates $name"
            Assert-True (Test-LegionLauncherExecutable -Path $path) "RefreshCreatesMissing makes $name executable"
            Assert-Equal $IsWindows (Test-Path -LiteralPath "$path.cmd") 'RefreshCreatesMissing creates missing batch shims only on Windows'
            $suffixes = if ($IsWindows) { @('', '.cmd') } else { @('') }
            foreach ($suffix in $suffixes) {
                $expected = Get-LegionShimText -App (Join-Path $alternateHome ".legion/app/$version") -Windows:([bool]$suffix) -HomeRoot $alternateHome
                Assert-Equal $expected ([IO.File]::ReadAllText("$path$suffix")) 'Refresh writes the whole generated command for the selected home'
            }
        }
    }
    $alternateBin = Join-Path $alternateHome '.legion/bin'
    $beforeMissing = @(Get-ChildItem $alternateBin -File | Sort-Object Name | ForEach-Object { $_.LastWriteTimeUtc.Ticks }) -join '|'
    $repeatMissing = @(& $refresh -HomeRoot $alternateHome)
    Assert-True ([bool]($repeatMissing -match '^skip: .*\(already done\)$')) 'RefreshCreatesMissing reports skip on the second run'
    Assert-Equal $beforeMissing (@(Get-ChildItem $alternateBin -File | Sort-Object Name | ForEach-Object { $_.LastWriteTimeUtc.Ticks }) -join '|') 'RefreshCreatesMissing writes nothing on the second run'

    # RefreshKeepsBlocked: a foreign command stays even while missing siblings are created.
    $blockedHome = Join-Path $tempRoot 'blocked home'
    $blockedBin = Join-Path $blockedHome '.legion/bin'
    New-Item -ItemType Directory -Path $blockedBin -Force | Out-Null
    foreach ($suffix in @('', '.cmd')) {
        [IO.File]::WriteAllText((Join-Path $blockedBin "legion$suffix"), 'foreign command')
    }
    & $refresh -HomeRoot $blockedHome | Out-Null
    foreach ($suffix in @('', '.cmd')) {
        Assert-Equal 'foreign command' ([IO.File]::ReadAllText((Join-Path $blockedBin "legion$suffix"))) 'RefreshKeepsBlocked preserves foreign command bytes'
    }

    $config = Join-Path $tempRoot '.legion/configuration'
    $bin = Join-Path $tempRoot '.legion/bin'
    $runtime = Join-Path $bin '.runtime/bin'
    New-Item -ItemType Directory -Path $config, $runtime -Force | Out-Null
    $file = Join-Path $config 'personalisation.json'
    @{
        agents=@(
            @{id='foundry-a';tool='claude';command=$(if ($IsWindows) { '~/.legion/bin/foundry-a.cmd' } else { '~/.legion/bin/foundry-a' });configDir='~/.legion/agents/foundry-a';provider=@{kind='foundry'}},
            @{id='external';tool='claude';command='~/custom/external';provider=@{kind='foundry'}}
        )
        projects=@{example=@{custom='keep'}}
    } | ConvertTo-Json -Depth 20 | Set-Content $file
    $ownerBytes = [IO.File]::ReadAllText($file)
    & {
        . (Join-Path $root 'plugins/legion/bin/lib/accounts.ps1')
        New-FoundryWrappers -Id foundry-a -Tool claude -HomeRoot $tempRoot
    }
    'stale runtime' | Set-Content (Join-Path $runtime 'legion-foundry.ps1')
    foreach ($name in @('foundry', 'tools')) {
        'stale library' | Set-Content (Join-Path $runtime "lib/$name.ps1")
    }
    "#!/bin/sh`n# Generated by legion: account foundry-a`nstale wrapper" | Set-Content (Join-Path $bin 'foundry-a')
    'custom wrapper' | Set-Content (Join-Path $bin 'external')
    $shim = Join-Path $bin 'legion'
    @'
#!/bin/sh
# Generated by legion: owner command
exec pwsh -NoProfile -File '/old/owner'"'"'s/cache/bin/legion.ps1' -Account chosen "$@"
'@ | Set-Content $shim
    $cmdShim = Join-Path $bin 'legion.cmd'
    ('@rem Generated by legion: owner command' + [Environment]::NewLine + '@pwsh -NoProfile -File "C:\old\cache\bin\legion.ps1" -Account chosen -Repo "\\server\team$\work folder" %*') | Set-Content $cmdShim
    $batchBefore = [IO.File]::ReadAllText($cmdShim)
    & $refresh -HomeRoot $tempRoot | Out-Null
    $homeFlag = & {
        . (Join-Path $root 'plugins/legion/bin/lib/accounts.ps1')
        '--home ' + (ConvertTo-LegionShellLiteral $tempRoot)
    }
    Assert-True ((Get-Content $shim -Raw).Contains($homeFlag)) 'R4 B4 refresh binds an older unbound command to the selected home'
    & $refresh -HomeRoot $tempRoot | Out-Null
    Assert-Equal 1 ([regex]::Matches((Get-Content $shim -Raw), '--home ').Count) 'R4 B4 refresh preserves one home binding'
    & $refresh -HomeRoot $tempRoot | Out-Null
    Assert-Equal ([IO.File]::ReadAllText((Join-Path $root 'plugins/legion/bin/legion-foundry.ps1'))) ([IO.File]::ReadAllText((Join-Path $runtime 'legion-foundry.ps1'))) 'Approved refresh updates copied runtime bytes'
    foreach ($name in @('foundry', 'tools')) {
        Assert-Equal ([IO.File]::ReadAllText((Join-Path $root "plugins/legion/bin/lib/$name.ps1"))) ([IO.File]::ReadAllText((Join-Path $runtime "lib/$name.ps1"))) "Refresh updates the $name library in the current runtime layout"
    }
    & {
        . (Join-Path $runtime 'legion-foundry.ps1') -NoRun
        Assert-Equal 'claude' (@(Get-LegionTools).id -join '|') 'Refreshed runner loads libraries and discovers its copied skill with the copied schema'
    }
    Assert-True ((Get-Content (Join-Path $bin 'foundry-a') -Raw).Contains('.runtime')) 'Refresh regenerates owned Foundry wrapper'
    foreach ($path in $(if ($IsWindows) { @($shim,$cmdShim) } else { @($shim) })) {
        $text = Get-Content $path -Raw
        $app = if ($path -eq $cmdShim) { "%~dp0..\app\$version" } else { Join-Path $tempRoot ".legion/app/$version" }
        Assert-True ($text.Contains($app)) 'Refresh retargets the existing legion shim to the app'
        Assert-True (-not $text.Contains('-Account chosen')) 'Refresh replaces hand-added shim arguments'
    }
    if ($IsWindows) { Assert-True (-not (Get-Content $cmdShim -Raw).Contains('-Repo ')) 'Refresh replaces hand-added batch arguments' }
    else { Assert-Equal $batchBefore ([IO.File]::ReadAllText($cmdShim)) 'Unix refresh leaves a stray batch command unchanged' }
    Assert-Equal $ownerBytes ([IO.File]::ReadAllText($file)) 'Refresh preserves owner settings bytes'
    Assert-Equal 'custom wrapper' (Get-Content (Join-Path $bin 'external')) 'External command remains untouched'
    [IO.File]::WriteAllText((Join-Path $bin 'legion'), 'unrelated owner command')
    & $refresh -HomeRoot $tempRoot | Out-Null
    Assert-Equal 'unrelated owner command' ([IO.File]::ReadAllText((Join-Path $bin 'legion'))) 'Refresh leaves an unrelated command untouched'
    $before = @(Get-ChildItem $bin -File -Recurse | Sort-Object FullName | ForEach-Object { $_.LastWriteTimeUtc.Ticks }) -join '|'
    $repeat = @(& $refresh -HomeRoot $tempRoot)
    Assert-True ([bool]($repeat -match '^skip: .*\(already done\)$')) 'Repeated refresh reports skip'
    Assert-Equal $before (@(Get-ChildItem $bin -File -Recurse | Sort-Object FullName | ForEach-Object { $_.LastWriteTimeUtc.Ticks }) -join '|') 'Repeated refresh writes nothing'
    # C-1: a file that only mentions the launcher in a comment or a later argument is not rewritten.
    $lookalike = "#!/bin/sh`n# pwsh -NoProfile -File '/old/cache/bin/legion.ps1'`necho mine"
    [IO.File]::WriteAllText((Join-Path $bin 'legion'), $lookalike)
    $argumentOnly = "#!/bin/sh`nexec pwsh -NoProfile -File /mine/tool.ps1 '/old/cache/bin/legion-status.ps1'`n"
    [IO.File]::WriteAllText((Join-Path $bin 'custom-status'), $argumentOnly)
    & $refresh -HomeRoot $tempRoot | Out-Null
    Assert-Equal $lookalike ([IO.File]::ReadAllText((Join-Path $bin 'legion'))) 'Refresh leaves a comment-only mention untouched'
    Assert-Equal $argumentOnly ([IO.File]::ReadAllText((Join-Path $bin 'custom-status'))) 'Refresh leaves a later-argument mention untouched'
    # C-2: an owned command whose script is gone is rewritten to the current one.
    $stale = "#!/bin/sh`n# Generated by legion: owner command`nexec pwsh -NoProfile -File '/gone/cache/bin/legion.ps1' -OwnerFlag keep `"`$@`"`n"
    [IO.File]::WriteAllText((Join-Path $bin 'legion'), $stale)
    & $refresh -HomeRoot $tempRoot | Out-Null
    $fixed = [IO.File]::ReadAllText((Join-Path $bin 'legion'))
    Assert-True ($fixed.Contains((Join-Path $tempRoot ".legion/app/$version")) -and -not $fixed.Contains('-OwnerFlag keep')) 'Refresh rewrites a marked command and discards hand-added flags'
    # Interim until task 5 ports refresh to Python: missing subscription launchers are rebuilt from the settings,
    # from the stored command when there is one and from the stock CLI on PATH when there is not.
    & {
        $scratch = Join-Path $tempRoot 'accounts'
        $savedPath = $env:PATH
        try {
            . (Join-Path $root 'plugins/legion/bin/lib/accounts.ps1')
            . (Join-Path $root 'tests/lib/workspace.ps1')
            $fakeBin = Join-Path $scratch 'fake tools'
            New-Item -ItemType Directory -Path $fakeBin -Force | Out-Null
            # Only fixture commands are discoverable, including the runner's inert uv throughout.
            $env:PATH = @($fakeBin, $fakeUvFolder) -join [IO.Path]::PathSeparator
            Assert-Equal $fakeUvFolder (Split-Path (Get-Command uv -CommandType Application | Select-Object -First 1).Source) 'T4-07 refresh keeps the runner fake uv available'
            $agents = @()
            foreach ($descriptor in Get-LegionTools) {
                $cli = Join-Path $fakeBin $(if ($IsWindows) { "$($descriptor.command).cmd" } else { $descriptor.command })
                $text = if ($IsWindows) { '@echo %' + $descriptor.configEnv + '%' + "`r`n@exit /b 0`r`n" }
                    else { '#!/bin/sh' + "`n" + 'echo "$' + $descriptor.configEnv + '"' + "`n" }
                [IO.File]::WriteAllText($cli, $text)
                Set-TestExecutable $cli
                $agents += @{ id = "$($descriptor.id)-a"; tool = $descriptor.id; configDir = "~/.legion/agents/$($descriptor.id)-a" }
            }
            $custom = Join-Path $scratch $(if ($IsWindows) { 'custom.cmd' } else { 'custom' })
            [IO.File]::WriteAllText($custom, $(if ($IsWindows) { "@echo custom`r`n@exit /b 0`r`n" } else { "#!/bin/sh`necho custom`n" }))
            Set-TestExecutable $custom
            $agents += @{ id = 'custom-a'; tool = 'codex'; configDir = '~/.legion/agents/custom-a'; command = $custom }
            $settings = Join-Path $scratch '.legion/configuration/personalisation.json'
            Write-LegionPersonalisation -Data ([pscustomobject]@{ schemaVersion = 1; agents = $agents; channels = @() }) -Path $settings
            $original = [IO.File]::ReadAllText($settings)
            $null = @(& $refresh -HomeRoot $scratch)
            foreach ($agent in $agents) {
                $wrapper = Join-Path $scratch ".legion/bin/$($agent.id)"
                Assert-True (Test-Path $wrapper) 'Refresh recreates missing account launchers from settings'
                Assert-True (Test-LegionLauncherExecutable $wrapper) 'Refreshed launcher is executable'
                $folder = Get-LegionNewAccountDir -Id $agent.id -HomeRoot $scratch
                $launched = if ($IsWindows) { & "$wrapper.cmd" } else { & $wrapper }
                if ($agent.id -eq 'custom-a') { Assert-Equal 'custom' "$launched" 'A stored command is never replaced by the stock CLI' }
                else { Assert-Equal $folder "$launched" 'Recovered launcher runs the fake CLI with its account config folder' }
            }
            Assert-Equal $original ([IO.File]::ReadAllText($settings)) 'Refresh leaves settings unchanged'
            $accountBin = Join-Path $scratch '.legion/bin'
            $accountBefore = @(Get-ChildItem $accountBin -File | Sort-Object Name | ForEach-Object { $_.LastWriteTimeUtc.Ticks }) -join '|'
            $accountRepeat = @(& $refresh -HomeRoot $scratch)
            Assert-True ($accountRepeat -contains 'skip: legion generated runtimes and launchers (already done)') 'Repeated refresh reports skip'
            Assert-Equal $accountBefore (@(Get-ChildItem $accountBin -File | Sort-Object Name | ForEach-Object { $_.LastWriteTimeUtc.Ticks }) -join '|') 'Repeated refresh changes no launcher timestamps'
            if ($IsWindows) {
                # The Python writer leaves this exact header and batch target form.
                $survivor = Join-Path $accountBin 'codex-a.cmd'
                $codexCli = Join-Path $fakeBin 'codex.cmd'
                $pythonText = "@rem Generated by legion: account codex-a`r`n@setlocal DisableDelayedExpansion`r`n@set `"CODEX_HOME=$(Get-LegionNewAccountDir -Id codex-a -HomeRoot $scratch)`"`r`n@set `"LEGION_ACCOUNT_TARGET=$($codexCli.Replace('%', '%%'))`"`r`n@call `"%%LEGION_ACCOUNT_TARGET%%`" %*`r`n@exit /b %errorlevel%`r`n"
                [IO.File]::WriteAllText($survivor, $pythonText)
                Remove-Item -LiteralPath (Join-Path $accountBin 'codex-a')
                $repaired = @(& $refresh -HomeRoot $scratch)
                Assert-True (Test-Path -LiteralPath (Join-Path $accountBin 'codex-a')) 'Python batch survivor repairs missing shell launcher'
                Assert-Equal (Get-LegionNewAccountDir -Id codex-a -HomeRoot $scratch) "$( & $survivor )" 'Python batch survivor retains stock target'
                Assert-Equal 0 @($repaired -match 'collision|target not found').Count 'Python batch survivor does not collide with refresh'
                $storedSurvivor = Join-Path $accountBin 'custom-a.cmd'
                [IO.File]::WriteAllText($storedSurvivor, $pythonText.Replace('codex-a', 'custom-a').Replace($codexCli, $custom))
                Remove-Item -LiteralPath (Join-Path $accountBin 'custom-a')
                $storedRepair = @(& $refresh -HomeRoot $scratch)
                Assert-True (Test-Path -LiteralPath (Join-Path $accountBin 'custom-a')) 'Python batch survivor repairs stored-command shell launcher'
                Assert-Equal 'custom' "$( & $storedSurvivor )" 'Python batch survivor retains stored target'
                Assert-Equal 0 @($storedRepair -match 'collision|target not found').Count 'Stored Python batch survivor does not collide with refresh'
            }
            # An unavailable CLI blocks only its account; the stored command's file gone blocks its own.
            Remove-Item -LiteralPath (Join-Path $fakeBin $(if ($IsWindows) { 'codex.cmd' } else { 'codex' }))
            Assert-Equal $fakeUvFolder (Split-Path (Get-Command uv -CommandType Application | Select-Object -First 1).Source) 'T4-07 missing CLI case retains fake uv'
            Assert-Equal $false ([bool](Get-Command codex -CommandType Application -ErrorAction SilentlyContinue)) 'T4-07 missing CLI lookup cannot reach a host command'
            Remove-Item -LiteralPath (Join-Path $accountBin 'codex-a')
            if ($IsWindows) { Remove-Item -LiteralPath (Join-Path $accountBin 'codex-a.cmd') }
            Remove-Item -LiteralPath (Join-Path $accountBin 'custom-a')
            if ($IsWindows) { Remove-Item -LiteralPath (Join-Path $accountBin 'custom-a.cmd') }
            Remove-Item -LiteralPath $custom
            $missing = @(& $refresh -HomeRoot $scratch)
            Assert-Equal 1 @($missing -match '^skip: account codex-a .*CLI.*not found').Count 'Missing CLI has one account-specific skip line'
            Assert-Equal 1 @($missing -match '^skip: account custom-a .*CLI.*not found').Count 'A stored command that is gone has one account-specific skip line'
            Assert-Equal $false (Test-Path (Join-Path $accountBin 'codex-a')) 'Missing CLI creates no launcher'
            Assert-Equal $false (Test-Path (Join-Path $accountBin 'custom-a')) 'A gone stored command creates no launcher'
            Assert-True (Test-Path (Join-Path $accountBin 'claude-a')) 'Other account launchers are retained'
        } finally { $env:PATH = $savedPath }
    }
} finally {
    if ([IO.Path]::GetFullPath($tempRoot).StartsWith([IO.Path]::GetFullPath((Join-Path $root '.agents/temp/')))) {
        Remove-Item -LiteralPath $tempRoot -Recurse -Force
    }
}
