$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot -Parent
$failures = @()
$cases = [ordered]@{
    RecordBeforeRefresh = {
        $plugin = Join-Path $sandbox 'plugin'
        New-Item -ItemType Directory -Path "$plugin/bin" -Force | Out-Null
        'throw "refresh failed"' | Set-Content "$plugin/bin/legion-refresh.ps1"
        function Invoke-ClosedInput { throw 'refresh failed' }
        Assert-Throws { Invoke-InstallRefresh -Entry $catalog.tools[0] -PluginRoot $plugin } 'Refresh failure propagates'
        $index = Join-Path $sandbox '.legion/footprints.json'
        Assert-True (Test-Path $index) 'The index exists before refresh can fail'
        $entry = (Get-Content $index -Raw | ConvertFrom-Json).entries | Where-Object path -EQ '~/.legion/bin/legion'
        Assert-Equal (Get-LegionTargetOwner -Tool $catalog.tools[0] -HomeRoot $sandbox) ($entry.owners -join '|') 'The target already owns the command'
    }
    SharedCommand = {
        $state.Only = 'claude'
        $command = Join-Path $sandbox '.legion/bin/legion'
        New-Item -ItemType Directory -Path (Split-Path $command) -Force | Out-Null
        "#!/bin/sh`n# Generated by legion: owner command" | Set-Content $command
        $claude = Get-LegionTargetOwner -Tool $catalog.tools[0] -HomeRoot $sandbox
        $codex = Get-LegionTargetOwner -Tool ($catalog.tools | Where-Object id -EQ codex) -HomeRoot $sandbox
        foreach ($owner in @($claude, $codex)) { Add-LegionFootprint -HomeRoot $sandbox -Kind file -Path $command -Owner $owner }
        $refreshed = [Collections.Generic.List[string]]::new()
        function Invoke-InstallRefresh {
            param($Entry, $ConfigDir)
            $refreshed.Add($Entry.id)
            "#!/bin/sh`n# Generated by legion: owner command`n# refreshed from codex" | Set-Content (Join-Path $sandbox '.legion/bin/legion')
        }
        $null = Invoke-LegionInstaller -Catalog $catalog -Tools claude -Uninstall -Yes
        Assert-True (Test-Path $command) 'First uninstall keeps a shared command'
        Assert-Equal 'codex' ($refreshed -join '|') 'First uninstall refreshes from the recorded remaining target'
        Assert-True ([IO.File]::ReadAllText((Join-Path $sandbox '.legion/bin/legion')).Contains('refreshed from codex')) 'Refresh rewrites the command'
        Assert-Equal $codex ((Get-LegionFootprints -HomeRoot $sandbox -Kind file).owners -join '|') 'Only the surviving target owns it'
        $state.Only = 'codex'; $state.Plugin = $true; $state.Marketplace = $true
        $null = Invoke-LegionInstaller -Catalog $catalog -Tools codex -Uninstall -Yes
        Assert-Equal $false (Test-Path $command) 'Last uninstall removes the command'
        $repeat = @(Invoke-LegionInstaller -Catalog $catalog -Tools codex -Uninstall -Yes) -join "`n"
        Assert-True ($repeat.Contains('skip: legion generated files (not installed)')) 'Repeat skips generated files'
    }
    SafeRemoval = {
        $bin = Join-Path $sandbox '.legion/bin'
        New-Item -ItemType Directory -Path $bin -Force | Out-Null
        $outside = Join-Path $sandbox 'owner-file'
        $foreign = Join-Path $bin 'foreign'
        "#!/bin/sh`n# Generated by legion: owner command" | Set-Content $outside
        'owner file' | Set-Content $foreign
        foreach ($path in @($outside, $foreign)) { Add-LegionFootprint -HomeRoot $sandbox -Kind file -Path $path -Owner target }
        $null = Remove-LegionFootprintOwner -HomeRoot $sandbox -Owner target
        Assert-True ((Test-Path $outside) -and (Test-Path $foreign)) 'Outside and headerless files stay'
        Assert-Equal 2 @(Get-LegionFootprints -HomeRoot $sandbox -Kind file).Count 'Rejected entries stay for a retry'
        $linked = Join-Path $bin 'linked'
        $destination = Join-Path $sandbox 'link-target'
        New-Item -ItemType Directory -Path $destination -Force | Out-Null
        "#!/bin/sh`n# Generated by legion: owner command" | Set-Content (Join-Path $destination 'legion')
        $type = if ($IsWindows) { 'Junction' } else { 'SymbolicLink' }
        New-Item -ItemType $type -Path $linked -Target $destination -ErrorAction Stop | Out-Null
        try {
            Add-LegionFootprint -HomeRoot $sandbox -Kind file -Path (Join-Path $linked 'legion') -Owner linked
            $null = Remove-LegionFootprintOwner -HomeRoot $sandbox -Owner linked
            Assert-True (Test-Path (Join-Path $destination 'legion')) 'A linked ancestor blocks deletion'
            Add-LegionFootprint -HomeRoot $sandbox -Kind folder -Path $bin -Owner folder
            $null = Remove-LegionFootprintOwner -HomeRoot $sandbox -Owner folder
            Assert-True (Test-Path $foreign) 'A folder with linked contents stays'
        } finally { (Get-Item -LiteralPath $linked -Force).Delete() }
    }
    HeaderlessUnrecorded = {
        $state.Only = 'claude'
        $command = Join-Path $sandbox '.legion/bin/legion'
        New-Item -ItemType Directory -Path (Split-Path $command) -Force | Out-Null
        $original = '#!/bin/sh' + "`n" + 'exec pwsh -NoProfile -File /plugin/bin/legion.ps1 "$@"'
        [IO.File]::WriteAllText($command, $original)
        $null = Invoke-LegionInstaller -Catalog $catalog -Tools claude -Uninstall -Yes
        Assert-True (Test-Path $command) 'An unrecorded headerless command is never deleted'
        Assert-Equal $original ([IO.File]::ReadAllText($command)) 'Headerless command bytes stay'
    }
    RuntimeOwners = {
        . (Join-Path $repo 'plugins/legion/bin/lib/accounts.ps1')
        foreach ($id in @('foundry-a', 'foundry-b')) { New-FoundryWrappers -Id $id -Tool claude -HomeRoot $sandbox }
        $runtime = Get-LegionOwnerPath -HomeRoot $sandbox -Name Runtime
        Move-LegionWrappers -OldId foundry-a -NewId foundry-c -HomeRoot $sandbox
        $owners = (Get-LegionFootprints -HomeRoot $sandbox -Kind folder).owners
        Assert-True ($owners -contains 'account:foundry-c' -and $owners -notcontains 'account:foundry-a') 'Rename transfers the runtime owner'
        Remove-LegionWrappers -Id foundry-c -HomeRoot $sandbox
        Assert-True (Test-Path $runtime) 'One account still needs the runtime'
        Remove-LegionWrappers -Id foundry-b -HomeRoot $sandbox
        Assert-Equal $false (Test-Path $runtime) 'Last account removes the runtime'
    }
    PurgeRecordedEdits = {
        $savedOS = $env:OS; $savedPath = $env:PATH
        try {
            $env:OS = 'Windows_NT'
            $bin = Join-Path $sandbox '.legion/bin'
            $az = Join-Path $sandbox '.legion/tools/az'
            $state.UserPath = "%USERPROFILE%\bin;$bin;$az"
            $env:PATH = @('%USERPROFILE%\bin', $bin, $az) -join [IO.Path]::PathSeparator
            function Get-LegionUserPath { $state.UserPath }
            function Set-LegionUserPath { param($Path) $state.UserPath = $Path }
            foreach ($path in @($bin, $az)) { Add-LegionFootprint -HomeRoot $sandbox -Kind path-entry -Path 'user PATH' -Value $path -Owner legion }
            $settings = Join-Path $sandbox '.claude/settings.json'
            $before = '{/*keep*/"permissions":{"allow":["Bash(LEGION_ROLE=member *)",/*other*/"Read(*)"]},"theme":"dark"}'
            [IO.File]::WriteAllText($settings, $before)
            $owner = Get-LegionTargetOwner -Tool $catalog.tools[0] -HomeRoot $sandbox
            Add-LegionFootprint -HomeRoot $sandbox -Kind edit -Path $settings -Key permissions.allow -Value 'Bash(LEGION_ROLE=member *)' -Owner $owner
            $state.Only = 'claude'
            $null = Invoke-LegionInstaller -Catalog $catalog -Tools claude -Uninstall -Yes
            Assert-Equal ($before.Replace('"Bash(LEGION_ROLE=member *)",', '')) ([IO.File]::ReadAllText($settings)) 'A1: uninstall undoes the target-owned rule through the same editor'
            Assert-Equal 2 @(Get-LegionFootprints -HomeRoot $sandbox -Kind path-entry).Count 'Uninstall keeps legion-owned PATH entries'
            [IO.File]::WriteAllText($settings, $before)
            Add-LegionFootprint -HomeRoot $sandbox -Kind edit -Path $settings -Key permissions.allow -Value 'Bash(LEGION_ROLE=member *)' -Owner $owner
            $preview = @(Invoke-LegionPurge -DryRun) -join "`n"
            Assert-True ($preview.Contains($az) -and $preview.Contains('Bash(LEGION_ROLE=member *)')) 'Preview lists recorded PATH and allow changes'
            $null = Invoke-LegionPurge -Yes
            Assert-Equal '%USERPROFILE%\bin' $state.UserPath 'Only the recorded PATH entries are removed'
            Assert-Equal '%USERPROFILE%\bin' $env:PATH 'The process PATH follows the same exact removal'
            Assert-Equal ($before.Replace('"Bash(LEGION_ROLE=member *)",', '')) ([IO.File]::ReadAllText($settings)) 'Comments and other rules stay byte for byte'
            Assert-Equal $false (Test-Path (Join-Path $sandbox '.legion/footprints.json')) 'Purge deletes the index last with the home'
        } finally { $env:OS = $savedOS; $env:PATH = $savedPath }
    }
    ExactHeader = {
        $command = Join-Path $sandbox '.legion/bin/legion'
        New-Item -ItemType Directory -Path (Split-Path $command) -Force | Out-Null
        $text = "#!/bin/sh`necho 'owner script; not # Generated by legion: owner command'`n"
        [IO.File]::WriteAllText($command, $text)
        Add-LegionFootprint -HomeRoot $sandbox -Kind file -Path $command -Owner target
        $null = Remove-LegionFootprintOwner -HomeRoot $sandbox -Owner target
        Assert-Equal $text ([IO.File]::ReadAllText($command)) 'B-c: the header text elsewhere in a file does not make it legion''s'
    }
    OwnerOnly = {
        $command = Join-Path $sandbox '.legion/bin/legion'
        New-Item -ItemType Directory -Path (Split-Path $command) -Force | Out-Null
        [IO.File]::WriteAllText($command, "#!/bin/sh`n# Generated by legion: owner command`n")
        Add-LegionFootprint -HomeRoot $sandbox -Kind file -Path $command -Owner gone
        # An entry left with no owners, as after a skipped removal.
        $index = Get-LegionOwnerPath -HomeRoot $sandbox -Name Index
        $data = Get-Content $index -Raw | ConvertFrom-Json
        $data.entries[0].owners = @()
        [IO.File]::WriteAllText($index, ($data | ConvertTo-Json -Depth 10))
        $output = @(Remove-LegionFootprintOwner -HomeRoot $sandbox -Owner other)
        Assert-True (Test-Path $command) 'B-h: removing one owner leaves an unrelated orphan alone'
        Assert-Equal 0 $output.Count 'B-h: nothing is printed for entries of other owners'
    }
    ExplicitEditRemover = {
        $settings = Join-Path $sandbox '.claude/settings.json'
        $removed = [Collections.Generic.List[string]]::new()
        Add-LegionFootprint -HomeRoot $sandbox -Kind edit -Path $settings -Key permissions.allow -Value rule -Owner target
        $null = Remove-LegionFootprintOwner -HomeRoot $sandbox -Owner target -RemoveEdit { param($Entry, $HomeRoot, [switch]$WhatIf) $removed.Add($Entry.value); $true }
        Assert-Equal 'rule' ($removed -join '|') 'F12: the caller passes the edit remover'
        Assert-Equal 0 @(Get-LegionFootprints -HomeRoot $sandbox -Kind edit).Count 'F12: an undone edit leaves the index'
        Add-LegionFootprint -HomeRoot $sandbox -Kind edit -Path $settings -Key permissions.allow -Value rule -Owner target
        $null = Remove-LegionFootprintOwner -HomeRoot $sandbox -Owner target
        Assert-Equal 1 @(Get-LegionFootprints -HomeRoot $sandbox -Kind edit).Count 'F12: without a remover the edit stays for uninstall or purge'
    }
    IndexLock = {
        $command = Join-Path $sandbox '.legion/bin/legion'
        Add-LegionFootprint -HomeRoot $sandbox -Kind file -Path $command -Owner first
        $index = Get-LegionOwnerPath -HomeRoot $sandbox -Name Index
        $started = Join-Path $sandbox 'writer-started'
        $lock = [IO.File]::Open("$index.lock", 'OpenOrCreate', 'ReadWrite', 'None')
        try {
            $job = Start-Job -ArgumentList (Join-Path $repo 'plugins/legion/bin/lib/footprints.ps1'), $sandbox, $command, $started -ScriptBlock {
                param($Library, $HomeRoot, $Command, $Started)
                . $Library
                [IO.File]::WriteAllText($Started, '')
                Add-LegionFootprint -HomeRoot $HomeRoot -Kind file -Path $Command -Owner second
            }
            while (-not (Test-Path $started) -and $job.State -eq 'Running') { Start-Sleep -Milliseconds 50 }
            Start-Sleep -Milliseconds 700
            Assert-Equal 'first' ((Get-LegionFootprints -HomeRoot $sandbox).owners -join '|') 'B-d: a second writer waits for the index lock'
        } finally { $lock.Dispose() }
        $null = $job | Wait-Job -Timeout 60 | Receive-Job
        Remove-Job $job -Force
        Assert-Equal 'first|second' ((Get-LegionFootprints -HomeRoot $sandbox).owners -join '|') 'B-d: the waiting writer adds its owner after the lock is released'
        if (-not $IsWindows) {
            # Windows cannot replace a file another handle has open; macOS and Linux show the replace.
            $before = [IO.File]::ReadAllText($index)
            $reader = [IO.StreamReader]::new($index)
            try {
                Add-LegionFootprint -HomeRoot $sandbox -Kind file -Path $command -Owner third
                $seen = $reader.ReadToEnd()
            } finally { $reader.Dispose() }
            Assert-Equal $before $seen 'B-d: the index is replaced whole, so an open reader keeps the complete old copy'
        }
    }
    ExistingUserPath = {
        $savedOS = $env:OS
        try {
            . (Join-Path $repo 'plugins/legion/bin/lib/paths.ps1')
            $env:OS = 'Windows_NT'
            $bin = Join-Path $sandbox '.legion/bin'
            $state.UserPath = "C:\owner;$bin"
            function Get-LegionUserPath { $state.UserPath }
            function Set-LegionUserPath { throw 'An existing entry needs no write' }
            $null = Add-LegionUserPath -Folder $bin -HomeRoot $sandbox
            Assert-Equal 0 @(Get-LegionFootprints -HomeRoot $sandbox).Count 'B-b: a user PATH entry the owner already had is not recorded'
        } finally { $env:OS = $savedOS }
    }
    ExistingAllowRule = {
        . (Join-Path $repo 'plugins/legion/bin/legion-setup.ps1') -NoRun
        $folder = Join-Path $sandbox 'owner-claude'
        New-Item -ItemType Directory -Path $folder -Force | Out-Null
        '{"permissions":{"allow":["Bash(LEGION_ROLE=member *)"]}}' | Set-Content (Join-Path $folder 'settings.json')
        $output = @(Add-SetupAllowRules -Plan @{ HomeRoot = $sandbox; Accounts = @(@{ Usable = $true; Tool = (Get-LegionTool -Tool claude); Folder = $folder }) })
        Assert-True (($output -join "`n").Contains('skip: permission rule')) 'An existing rule is a skip'
        Assert-Equal 0 @(Get-LegionFootprints -HomeRoot $sandbox -Kind edit).Count 'B-b: an allow rule the owner already had is not recorded'
    }
    LinkedTargetOwner = {
        # A linked config-folder spelling and its physical spelling are one install target.
        $physical = Join-Path $sandbox 'physical-claude'
        $linked = Join-Path $sandbox 'linked-claude'
        New-Item -ItemType Directory -Path $physical -Force | Out-Null
        $type = if ($IsWindows) { 'Junction' } else { 'SymbolicLink' }
        New-Item -ItemType $type -Path $linked -Target (Resolve-LegionDirectoryPath $physical) | Out-Null
        try {
            Assert-Equal (Get-LegionTargetOwner -Tool $catalog.tools[0] -Folder $physical -HomeRoot $sandbox) (Get-LegionTargetOwner -Tool $catalog.tools[0] -Folder $linked -HomeRoot $sandbox) 'Linked and physical spellings give one owner id'
        } finally { [IO.Directory]::Delete($linked) }
    }
    RecordIsIdempotent = {
        $path = Join-Path $sandbox '.legion/bin/legion'
        Add-LegionFootprint -HomeRoot $sandbox -Kind file -Path $path -Owner target
        $index = Get-LegionOwnerPath -HomeRoot $sandbox -Name Index
        $before = [Convert]::ToBase64String([IO.File]::ReadAllBytes($index))
        $stamp = (Get-Item $index).LastWriteTimeUtc.Ticks
        Add-LegionFootprint -HomeRoot $sandbox -Kind file -Path $path -Owner target
        Assert-Equal $before ([Convert]::ToBase64String([IO.File]::ReadAllBytes($index))) 'Recording again keeps the bytes'
        Assert-Equal $stamp (Get-Item $index).LastWriteTimeUtc.Ticks 'Recording again does not write'
    }
}
foreach ($case in $cases.GetEnumerator()) {
    try {
        & {
            . (Join-Path $PSScriptRoot 'fixtures/install/UninstallSandbox.ps1')
            try { & $case.Value } finally { Remove-UninstallSandbox }
        }
        "PASS $($case.Key)"
    } catch { $failures += "$($case.Key): $($_.Exception.Message)"; "FAIL $($failures[-1])" }
}
if ($failures.Count) { throw ($failures -join "`n") }
