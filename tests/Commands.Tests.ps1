$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
. (Join-Path $root 'plugins/legion/bin/lib/commands.ps1')
Assert-Equal 'legion' ((Get-LegionCommandState -Bin $root -HomeRoot $root).Name | Select-Object -Unique) 'Only the legion owner command is published'
$scratch = Join-Path $root ('.agents/temp/commands-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $scratch -Force | Out-Null
try {
    $target = Join-Path $scratch "owner's 100% home/.legion/app/1.2.3"
    $environment = Get-LegionPythonEnvironment -PluginRoot $target -HomeRoot $scratch
    $missing = 'uv is missing. Ask the owner before installing it, then run the legion installer again.'
    $unix = Get-LegionShimText -App $target -HomeRoot $scratch
    $expected = "#!/bin/sh`n# Generated by legion: owner command`n" +
        "command -v uv >/dev/null 2>&1 || { echo '$missing' >&2; exit 127; }`n" +
        'export UV_PROJECT_ENVIRONMENT=' + (ConvertTo-LegionShellLiteral $environment) + "`n" +
        'exec uv run --project ' + (ConvertTo-LegionShellLiteral $target) + ' --frozen --quiet legion --home ' + (ConvertTo-LegionShellLiteral $scratch) + ' "$@"' + "`n"
    Assert-Equal $expected $unix 'Shell command runs the app through uv, with the app and selected home quoted literally'
    if (-not $IsWindows) {
        $missingUv = Join-Path $scratch 'missing-uv'
        [IO.File]::WriteAllText($missingUv, $unix)
        $output = @(& /usr/bin/env PATH=/nonexistent /bin/sh $missingUv status 2>&1 | ForEach-Object { "$_" })
        Assert-Equal 127 $LASTEXITCODE 'Without uv the shell command exits 127'
        Assert-Equal $missing ($output -join "`n") 'Without uv the shell command prints one plain line'
    }
    $unixDefault = Get-LegionShimText -App $target
    Assert-True (-not $unixDefault.Contains('--home') -and $unixDefault.Contains((ConvertTo-LegionShellLiteral (Get-LegionPythonEnvironment -PluginRoot $target)))) 'The default home adds no --home and uses the default environment'
    $windows = Get-LegionShimText -App $target -HomeRoot $scratch -Windows
    $expectedWindows = "@rem Generated by legion: owner command`r`n" +
        "@where /q uv || (>&2 echo $missing& exit /b 127)`r`n" +
        "@set `"UV_PROJECT_ENVIRONMENT=%~dp0..\python\$(Split-Path $environment -Leaf)`" & uv run --project `"%~dp0..\app\1.2.3`" --frozen --quiet legion --home `"%~dp0..\..`" %* & (goto) 2>nul & " +
        "set `"UV_PROJECT_ENVIRONMENT=%UV_PROJECT_ENVIRONMENT%`" & `"%COMSPEC%`" /d /c `"set /a LEGION_EXIT=0x%%=ExitCode%% >nul & call exit %%^LEGION_EXIT%%`"`r`n"
    Assert-True ($target.Contains('%') -and -not $windows.Contains('100%')) 'The batch command holds no home path, so a percent sign in it needs no escape'
    Assert-Equal $expectedWindows $windows 'Batch command finds its paths from its own folder, restores its environment and keeps the safe deletion tail'
    $path = Join-Path $scratch 'legion'
    Assert-Equal 'missing' (Get-LegionOwnerCommandState -Path $path) 'Missing file'
    $cmdPath = "$path.cmd"
    foreach ($case in @(@($path, $unix), @($path, ($unix + 'extra flags')), @($cmdPath, $windows), @($cmdPath, ($windows + '@echo extra')))) {
        [IO.File]::WriteAllText($case[0], $case[1])
        Assert-True (Test-LegionOwnerCommandFile -Path $case[0]) 'The header owns the whole file, including hand-added text'
    }
    foreach ($case in @(@($path, 'owner file'), @($path, 'pwsh -NoProfile -File /plugin/bin/legion.ps1'), @($path, '#!/bin/sh'),
            @($path, "# Generated by legion: owner command`necho changed"), @($path, "#!/bin/sh`necho '# Generated by legion: owner command'"),
            @($path, $windows), @($cmdPath, $unix), @($cmdPath, "@echo off`r`n@rem Generated by legion: owner command"))) {
        [IO.File]::WriteAllText($case[0], $case[1])
        Assert-Equal 'blocked' (Get-LegionOwnerCommandState -Path $case[0]) 'B-c: only the exact header at its position owns the file'
    }
    Remove-Item -LiteralPath $cmdPath
    Assert-Equal $false (Test-LegionOwnerCommandFile -Path $scratch) 'A directory is not a command file'
    $files = if ($IsWindows) { @('legion', 'legion.cmd') } else { @('legion') }
    foreach ($name in $files) {
        $file = Join-Path $scratch $name
        [IO.File]::WriteAllText($file, (Get-LegionShimText -App $target -HomeRoot $scratch -Windows:$name.EndsWith('.cmd')))
        if (-not $IsWindows) { [IO.File]::SetUnixFileMode($file, [IO.UnixFileMode]::UserRead -bor [IO.UnixFileMode]::UserWrite -bor [IO.UnixFileMode]::UserExecute) }
    }
    $states = @(Get-LegionCommandState -Bin $scratch -HomeRoot $scratch)
    Assert-Equal $files.Count $states.Count 'One row per platform command'
    Assert-Equal 'owned' (($states.State | Select-Object -Unique) -join '|') 'Header ownership does not depend on a parsed target'
    if (-not $IsWindows) {
        [IO.File]::SetUnixFileMode($path, [IO.UnixFileMode]::UserRead -bor [IO.UnixFileMode]::UserWrite)
        Assert-Equal 'permission' (Get-LegionCommandState -Bin $scratch -HomeRoot $scratch).State 'Executable permission is still checked'
    }
} finally {
    if (-not [IO.Path]::GetFullPath($scratch).StartsWith([IO.Path]::GetFullPath((Join-Path $root '.agents/temp/')))) { throw 'Unsafe command fixture cleanup' }
    Remove-Item -LiteralPath $scratch -Recurse -Force
}
