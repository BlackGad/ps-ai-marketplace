$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
. (Join-Path $root 'plugins/legion/bin/lib/commands.ps1')
Assert-Equal 'legion' ((Get-LegionOwnerCommands).Keys -join '|') 'Only the legion owner command is published'
$scratch = Join-Path $root ('.agents/temp/commands-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $scratch -Force | Out-Null
try {
    $target = Join-Path $scratch "owner's 100% plugin/bin/legion.ps1"
    $unix = Get-LegionShimText -Script $target -HomeRoot $scratch
    $expected = "#!/bin/sh`n# Generated by legion: owner command`n" + 'exec pwsh -NoProfile -File ' + (ConvertTo-LegionShellLiteral $target) + ' -HomeRoot ' + (ConvertTo-LegionShellLiteral $scratch) + ' "$@"' + "`n"
    Assert-Equal $expected $unix 'Shell launcher quotes the script and selected home literally'
    $windows = Get-LegionShimText -Script 'C:\plugin 100%\bin\legion.ps1' -Windows
    Assert-Equal "@rem Generated by legion: owner command`r`n@pwsh -NoProfile -File `"C:\plugin 100%%\bin\legion.ps1`" %* & (goto) 2>nul & exit /b`r`n" $windows 'Batch launcher has its header, percent escaping, and safe deletion tail'
    $path = Join-Path $scratch 'legion'
    Assert-Equal 'missing' (Get-LegionOwnerCommandState -Path $path) 'Missing file'
    foreach ($text in @($unix, $windows, "# Generated by legion`necho changed", ($unix + 'extra flags'))) {
        [IO.File]::WriteAllText($path, $text)
        Assert-True (Test-LegionOwnerCommandFile -Path $path) 'The header owns the whole file, including hand-added text'
    }
    foreach ($text in @('owner file', 'pwsh -NoProfile -File /plugin/bin/legion.ps1', '#!/bin/sh')) {
        [IO.File]::WriteAllText($path, $text)
        Assert-Equal 'blocked' (Get-LegionOwnerCommandState -Path $path) 'A headerless file is never adopted'
    }
    Assert-Equal $false (Test-LegionOwnerCommandFile -Path $scratch) 'A directory is not a command file'
    $files = if ($IsWindows) { @('legion', 'legion.cmd') } else { @('legion') }
    foreach ($name in $files) {
        $file = Join-Path $scratch $name
        [IO.File]::WriteAllText($file, (Get-LegionShimText -Script $target -HomeRoot $scratch -Windows:$name.EndsWith('.cmd')))
        if (-not $IsWindows) { [IO.File]::SetUnixFileMode($file, [IO.UnixFileMode]::UserRead -bor [IO.UnixFileMode]::UserWrite -bor [IO.UnixFileMode]::UserExecute) }
    }
    $states = @(Get-LegionCommandState -Bin $scratch -HomeRoot $scratch)
    Assert-Equal $files.Count $states.Count 'One row per platform command'
    Assert-Equal 'owned' (($states.State | Select-Object -Unique) -join '|') 'Header ownership does not depend on a parsed target'
    if (-not $IsWindows) {
        [IO.File]::SetUnixFileMode($path, [IO.UnixFileMode]::UserRead -bor [IO.UnixFileMode]::UserWrite)
        Assert-Equal 'permission' (Get-LegionCommandState -Bin $scratch -HomeRoot $scratch).State 'Executable permission is still checked'
    }
} finally {
    if (-not [IO.Path]::GetFullPath($scratch).StartsWith([IO.Path]::GetFullPath((Join-Path $root '.agents/temp/')))) { throw 'Unsafe command fixture cleanup' }
    Remove-Item -LiteralPath $scratch -Recurse -Force
}
