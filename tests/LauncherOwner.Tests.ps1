$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
. (Join-Path $root 'plugins/legion/bin/lib/accounts.ps1')
. (Join-Path $PSScriptRoot 'lib/paths.ps1')
$scratch = Join-Path $root ('.agents/temp/launcher-owner-' + [guid]::NewGuid().ToString('N'))
$homeRoot = Join-Path $scratch 'home'
$bin = Join-Path $homeRoot '.legion/bin'
New-Item -ItemType Directory -Path $bin, (Join-Path $scratch 'config') -Force | Out-Null
try {
    # One text owner: header, line ending and body come from Get-LegionLauncherText.
    Assert-Equal "#!/bin/sh`n# Generated by legion: account a-b`nexec x`n" (Get-LegionLauncherText -Id a-b -Body 'exec x') 'Shell launcher text'
    Assert-Equal "@rem Generated by legion: account a-b`r`n@x`r`n@y`r`n" (Get-LegionLauncherText -Id a-b -Body '@x', '@y' -Windows) 'Batch launcher text'

    # Rename gives the same launcher text as a fresh launcher for the new id, for both kinds of account.
    $fake = Join-Path $scratch 'tool.ps1'
    'exit 0' | Set-Content -LiteralPath $fake
    $config = Join-Path $scratch 'config'
    function Sync-LegionFoundryRuntime { param($Tool, $HomeRoot, $Changes) return (Join-Path $scratch 'runtime/legion-foundry.ps1') }
    $suffixes = if ($IsWindows) { @('', '.cmd') } else { @('') }
    $kinds = @{
        subscription = { param($Id) New-LegionWrappers -Id $Id -Tool claude -HomeRoot $homeRoot -RealCommand $fake -ConfigDir $config }
        foundry = { param($Id) New-FoundryWrappers -Id $Id -Tool claude -HomeRoot $homeRoot }
    }
    foreach ($kind in $kinds.Keys) {
        & $kinds[$kind] 'new-one'
        $fresh = @{}
        foreach ($suffix in $suffixes) { $fresh[$suffix] = [IO.File]::ReadAllText((Join-Path $bin "new-one$suffix")) }
        Remove-LegionWrappers -Id 'new-one' -HomeRoot $homeRoot
        & $kinds[$kind] 'old-one'
        Move-LegionWrappers -OldId 'old-one' -NewId 'new-one' -HomeRoot $homeRoot
        foreach ($suffix in $suffixes) {
            Assert-True (-not (Test-Path -LiteralPath (Join-Path $bin "old-one$suffix"))) "Rename removes the old $kind launcher '$suffix'"
            Assert-Equal $fresh[$suffix] ([IO.File]::ReadAllText((Join-Path $bin "new-one$suffix"))) "Renamed $kind launcher '$suffix' equals a fresh one"
        }
        Remove-LegionWrappers -Id 'new-one' -HomeRoot $homeRoot
    }
} finally {
    Remove-Item -LiteralPath $scratch -Recurse -Force -ErrorAction SilentlyContinue
}
