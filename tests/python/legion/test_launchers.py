# A launcher that lost its execute permission is still ours and intact: only the permission is given back.
@posix_only
def test_restore_execute_gives_the_permission_back_and_keeps_the_text(home: Path) -> None:
    account = agent("codex-a", home / "a")
    (path,) = _launchers.write_subscription(account, codex(), home)
    before = path.read_bytes()
    assert _launchers.restore_execute(account, home) == []
    path.chmod(path.stat().st_mode & ~stat.S_IXUSR)
    assert _launchers.launcher_state(account, home) == "intact"
    assert _launchers.restore_execute(account, home) == [path]
    assert path.stat().st_mode & stat.S_IXUSR
    assert path.read_bytes() == before


def test_move_replaces_only_the_header_line(home: Path) -> None:
    old, new = agent("old-one", home / "a"), agent("new-one", home / "a")
    old_paths = _launchers.write_subscription(old, codex(), home)
    _launchers.move("old-one", "new-one", home)
    assert not any(path.exists() for path in old_paths)
    moved = {path.name: path.read_bytes() for path in _launchers.launcher_paths("new-one", home)}
    # The same files written fresh for the new id are byte for byte the moved ones.
    fresh_home = home.parent / "fresh"
    fresh_home.mkdir()
    fresh = {path.name: path.read_bytes() for path in _launchers.write_subscription(new, codex(), fresh_home)}
    assert moved == fresh
    for path in _launchers.launcher_paths("new-one", home):
        assert _generated.is_owned(path, "account new-one")


def test_move_refuses_an_existing_destination_and_changes_nothing(home: Path) -> None:
    old_paths = _launchers.write_subscription(agent("old-one", home / "a"), codex(), home)
    blocked = bin_folder(home) / "new-one"
    blocked.write_text("owner file\n", encoding="utf-8")
    with pytest.raises(_launchers.LauncherError, match=r"^wrapper collision "):
        _launchers.move("old-one", "new-one", home)
    assert all(path.exists() for path in old_paths)
    assert blocked.read_text(encoding="utf-8") == "owner file\n"


def test_remove_deletes_owned_launchers_only(home: Path) -> None:
    paths = _launchers.write_subscription(agent("codex-a", home / "a"), codex(), home)
    foreign = bin_folder(home) / "codex-a"
    if WINDOWS:
        foreign.unlink()
        foreign.write_text("owner file\n", encoding="utf-8")
    _launchers.remove("codex-a", home)
    assert [path.exists() for path in paths] == ([True, False] if WINDOWS else [False])
    assert not WINDOWS or foreign.read_text(encoding="utf-8") == "owner file\n"


# Each launcher runs the target it names: arguments literally, the config variable set, the exit code passed on.
@pytest.mark.parametrize("kind", ["cli", "exe", "ps1"])
def test_each_launcher_runs_its_target(home: Path, tmp_path: Path, stock: Path, kind: str, pwsh_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    folder = home / "account folder"
    arguments = ["first", "two words"]
    if kind == "exe":
        script = python_cli(tmp_path / "py")
        command, arguments = Path(sys.executable), [str(script), *arguments]
    elif kind == "ps1":
        command = tmp_path / "prompt folder" / "worker prompt.ps1"
        command.parent.mkdir()
        command.write_text('Write-Output ("var=" + $env:CODEX_HOME)\nforeach ($word in $args) { Write-Output ("arg=" + $word) }\nexit 3\n', encoding="utf-8")
        only_on_path(monkeypatch, stock.parent, pwsh_path.parent)
        arguments = ["-Worker", "--prompt", str(tmp_path / "prompt folder" / "task prompt.txt"), "--allow-all-tools", "--allow-all-paths", *arguments]
    else:
        command = stock
    account = agent("codex-a", folder, command=str(command))
    _launchers.write_subscription(account, codex(), home)
    result = run_command(str(wrapper_command("codex-a", home)), arguments, timeout=60)
    assert result.exit_code == 3, result.error
    lines = [line.strip('"') for line in result.output.splitlines()] if kind == "cli" else result.output.splitlines()
    assert lines[0] == f"var={folder}"
    expected = arguments[1:] if kind == "exe" else arguments
    assert lines[1:] == [f"arg={word}" for word in expected]


@windows_only
@pytest.mark.parametrize("delayed", ["off", "on"])
def test_batch_target_keeps_percent_and_bang_paths(home: Path, tmp_path: Path, delayed: str) -> None:
    home = tmp_path / "owner! root"
    home.mkdir()
    command = fake_cli(tmp_path / "%TEMP% ! target", "fake")
    folder = home / "%TEMP% ! config"
    _launchers.write_subscription(agent("codex-a", folder, command=str(command)), codex(), home)
    # Enter the launcher folder before enabling delayed expansion so ! in the path stays literal.
    driver = tmp_path / "driver.cmd"
    launcher = wrapper_command("codex-a", home).name
    setting = "EnableDelayedExpansion" if delayed == "on" else "DisableDelayedExpansion"
    launcher_folder = _generated.cmd_escape(str(wrapper_command("codex-a", home).parent))
    driver_lines = ["@echo off", "@setlocal DisableDelayedExpansion", f'@cd /d "{launcher_folder}"', f"@setlocal {setting}", f'@call ".\\{launcher}" first "two words"']
    driver.write_text("\r\n".join(driver_lines) + "\r\n", encoding="utf-8", newline="")
    result = run_command(str(driver), [], timeout=60)
    assert result.exit_code == 3, result.error
    assert [line.strip('"') for line in result.output.splitlines()] == [f"var={folder}", "arg=first", "arg=two words"]
