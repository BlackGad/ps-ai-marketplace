def test_recursion_through_an_alias_is_refused_before_rewriting(home: Path, bin_alias: Path) -> None:
    account = agent("codex-a", home / "a")
    _launchers.write_subscription(account, codex(), home)
    paths = _launchers.launcher_paths(account.id, home)
    before = [path.read_bytes() for path in paths]
    account.command = str(bin_alias / wrapper_command(account.id, home).name)
    with pytest.raises(_launchers.LauncherError, match="wrapper target would recurse"):
        _launchers.write_subscription(account, codex(), home)
    assert [path.read_bytes() for path in paths] == before


