def test_launcher_state_tells_intact_none_and_partial_apart(home: Path) -> None:
    account = agent("codex-a", home / "a")
    assert _launchers.launcher_state(account, home) == "none"
    paths = _launchers.write_subscription(account, codex(), home)
    assert _launchers.launcher_state(account, home) == "intact"
    # Windows has two launchers; one of them gone is the partial case there.
    if WINDOWS:
        paths[0].unlink()
        assert _launchers.launcher_state(account, home) == "partial"
    # A file that is not ours does not count as a launcher.
    for path in paths:
        path.unlink(missing_ok=True)
    paths[0].write_text("owner file\n", encoding="utf-8")
    assert _launchers.launcher_state(account, home) == "partial"


