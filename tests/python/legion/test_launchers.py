def test_windows_launcher_text_for_each_target_kind() -> None:
    def text(target: str, folder: str = "C:\\a") -> str:
        return _launchers.subscription_text("codex-a", "CODEX_HOME", folder, target, windows=True)

    head = '@rem Generated by legion: account codex-a\r\n@setlocal DisableDelayedExpansion\r\n@set "CODEX_HOME=C:\\a"\r\n'
    tail = "\r\n@exit /b %errorlevel%\r\n"
    assert text("C:\\t\\codex.exe") == head + '@"C:\\t\\codex.exe" %*' + tail
    assert text("C:\\t\\codex.cmd") == head + '@set "LEGION_ACCOUNT_TARGET=C:\\t\\codex.cmd"\r\n@call "%%LEGION_ACCOUNT_TARGET%%" %*' + tail
    assert text("C:\\t\\codex.BAT") == head + '@set "LEGION_ACCOUNT_TARGET=C:\\t\\codex.BAT"\r\n@call "%%LEGION_ACCOUNT_TARGET%%" %*' + tail
    assert text("C:\\t\\codex.ps1") == head + '@pwsh -NoProfile -File "C:\\t\\codex.ps1" %*' + tail
    assert text("C:\\100%\\codex.exe", "C:\\a %b%") == (
        '@rem Generated by legion: account codex-a\r\n@setlocal DisableDelayedExpansion\r\n@set "CODEX_HOME=C:\\a %%b%%"\r\n@"C:\\100%%\\codex.exe" %*' + tail
    )


def test_windows_launcher_is_crlf_with_the_header_first() -> None:
    text = _launchers.subscription_text("codex-a", "CODEX_HOME", "C:\\a", "C:\\t\\codex.exe", windows=True)
    assert text.splitlines()[0] == _generated.header("account codex-a", True)
    assert text.count("\r\n") == len(text.splitlines())
    assert "\n" not in text.replace("\r\n", "")


def test_posix_launcher_text_quotes_every_literal() -> None:
    def text(target: str, folder: str = "/a b") -> str:
        return _launchers.subscription_text("codex-a", "CODEX_HOME", folder, target, windows=False)

    head = "#!/bin/sh\n# Generated by legion: account codex-a\n"
    assert text("/t/codex") == head + "CODEX_HOME='/a b' exec '/t/codex' \"$@\"\n"
    assert text("/o'k/codex", "/$(x)") == head + "CODEX_HOME='/$(x)' exec '/o'\"'\"'k/codex' \"$@\"\n"
    assert text("/t/codex.ps1") == head + "CODEX_HOME='/a b' exec pwsh -NoProfile -File '/t/codex.ps1' \"$@\"\n"


