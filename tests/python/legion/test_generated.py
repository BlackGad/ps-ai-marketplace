from pathlib import Path

from legion.core import _generated


def test_generated_file_ownership_and_repeat(tmp_path: Path) -> None:
    target = tmp_path / "legion"
    text = "#!/bin/sh\n# Generated by legion: owner command\necho ready\n"
    assert _generated.write_generated(target, text, executable=True)
    assert _generated.is_owned(target, "owner command")
    assert not _generated.write_generated(target, text, executable=True)
    assert _generated.shell_literal("it's") == "'it'\"'\"'s'"


def test_crlf_generated_file_is_unchanged_on_repeat(tmp_path: Path) -> None:
    target = tmp_path / "owner.cmd"
    text = "@rem Generated by legion: owner command\r\necho ready\r\n"
    assert _generated.write_generated(target, text, executable=False)
    assert not _generated.write_generated(target, text, executable=False)
    assert target.read_bytes() == text.encode("utf-8")
