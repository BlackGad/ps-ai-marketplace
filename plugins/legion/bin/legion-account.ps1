function Sync-LegionFoundryRuntime {
    param([string]$Tool, [string]$HomeRoot, [Collections.Generic.List[string]]$Changes)
    $descriptor = Get-LegionTool -Tool $Tool
    if ($null -eq $descriptor.foundry) { throw "tool '$Tool' does not support Foundry" }
    $runtime = [IO.Path]::GetFullPath((Get-LegionOwnerPath -HomeRoot $HomeRoot -Name Runtime))
    if (-not (Test-LegionOwnerPathSafe $runtime)) { throw 'Runtime path contains a link; resolve it before refreshing' }
    $pluginRoot = Split-Path $PSScriptRoot -Parent
    $files = [ordered]@{}
    foreach ($name in @('lib/tools.ps1', 'lib/foundry.ps1', 'lib/paths.ps1')) {
        $files["bin/$name"] = Join-Path $PSScriptRoot $name
    }
    $files['schemas/tool.schema.json'] = Join-Path $pluginRoot 'schemas/tool.schema.json'
    foreach ($name in @('SKILL.md', 'tool.json')) {
        $files["skills/legion-$Tool/$name"] = Join-Path $descriptor.SkillRoot $name
    }
    foreach ($script in Get-ChildItem -LiteralPath (Join-Path $descriptor.SkillRoot 'scripts') -File -Filter 'foundry-*.ps1') {
        $files["skills/legion-$Tool/scripts/$($script.Name)"] = $script.FullName
    }
    # Publish the runner only after its dependencies exist.
    $files['bin/legion-foundry.ps1'] = Join-Path $PSScriptRoot 'legion-foundry.ps1'
    foreach ($relativePath in $files.Keys) {
        $target = Join-Path $runtime $relativePath
        if (-not (Test-LegionOwnerPathSafe $target)) { throw 'Runtime file contains a link; resolve it before refreshing' }
        $bytes = [IO.File]::ReadAllBytes($files[$relativePath])
        if ((Test-Path -LiteralPath $target) -and [Convert]::ToBase64String([IO.File]::ReadAllBytes($target)) -ceq [Convert]::ToBase64String($bytes)) { continue }
        New-Item -ItemType Directory -Path (Split-Path $target -Parent) -Force | Out-Null
        [IO.File]::WriteAllBytes($target, $bytes)
        if ($null -ne $Changes) { $Changes.Add($target) }
    }
    $legacy = Get-LegionOwnerPath -HomeRoot $HomeRoot -Name Runtime -Legacy
    if ((Test-Path -LiteralPath $legacy) -and (Test-LegionOwnerPathSafe $legacy)) {
        # Remove only files this runtime publishes, including their pre-D1 names.
        foreach ($relativePath in $files.Keys) {
            foreach ($name in @($relativePath, $relativePath.Replace('legion-', 'ps-ai-'))) {
                $old = Join-Path $legacy $name
                if ((Test-Path -LiteralPath $old -PathType Leaf) -and (Test-LegionOwnerPathSafe $old)) {
                    Remove-Item -LiteralPath $old -Force
                    if ($null -ne $Changes) { $Changes.Add($old) }
                }
            }
        }
        $folders = @(Get-ChildItem -LiteralPath $legacy -Directory -Recurse -Force | Sort-Object { $_.FullName.Length } -Descending | ForEach-Object FullName) + @($legacy)
        foreach ($folder in $folders) {
            if ((Test-LegionOwnerPathSafe $folder) -and -not @(Get-ChildItem -LiteralPath $folder -Force).Count) { Remove-Item -LiteralPath $folder -Force }
        }
    }
    return Join-Path $runtime 'bin/legion-foundry.ps1'
}

function New-FoundryWrappers {
    param([string]$Id, [string]$HomeRoot, [string]$Tool, [Collections.Generic.List[string]]$Changes)
    Assert-LegionId $Id
    foreach ($suffix in @('', '.cmd')) { Assert-LegionWrapperPath (Get-LegionHomePath -HomeRoot $HomeRoot -Path "bin/$Id$suffix") $Id }
    $runner = Sync-LegionFoundryRuntime -Tool $Tool -HomeRoot $HomeRoot -Changes $Changes
    $bin = Get-LegionHomePath -HomeRoot $HomeRoot -Path 'bin'
    $shPath = ConvertTo-LegionShellLiteral $runner
    $sh = '#!/bin/sh' + "`n# Generated by legion: account $Id`n" + ('exec pwsh -NoProfile -File {0} -Agent {1} "$@"' -f $shPath, $Id) + "`n"
    Write-LegionGeneratedFile -Path (Join-Path $bin $Id) -Content $sh -Changes $Changes -Executable
    $cmd = "@rem Generated by legion: account $Id`r`n@pwsh -NoProfile -File `"$($runner.Replace('%', '%%'))`" -Agent $Id %*`r`n"
    Write-LegionGeneratedFile -Path (Join-Path $bin "$Id.cmd") -Content $cmd -Changes $Changes
}

