function Sync-LegionFoundryRuntime {
    param([string]$Tool, [string]$HomeRoot, [Collections.Generic.List[string]]$Changes)
    $descriptor = Get-LegionFoundryTool -Tool $Tool
    $runtime = [IO.Path]::GetFullPath((Get-LegionOwnerPath -HomeRoot $HomeRoot -Name Runtime))
    if (-not (Test-LegionOwnerPathSafe $runtime -StopRoot $HomeRoot)) { throw 'Runtime path contains a link; resolve it before refreshing' }
    $binRoot = Split-Path $PSScriptRoot -Parent
    $pluginRoot = Split-Path $binRoot -Parent
    $files = [ordered]@{}
    foreach ($name in (Get-LegionRuntimeFiles | Where-Object { $_ -ne 'bin/legion-foundry.ps1' })) {
        $files[$name] = Join-Path $pluginRoot $name
    }
    foreach ($name in @('SKILL.md', 'tool.json')) {
        $files["skills/legion-$Tool/$name"] = Join-Path $descriptor.SkillRoot $name
    }
    foreach ($script in Get-ChildItem -LiteralPath (Join-Path $descriptor.SkillRoot 'scripts') -File -Filter 'foundry-*.ps1') {
        $files["skills/legion-$Tool/scripts/$($script.Name)"] = $script.FullName
    }
    # Publish the runner only after its dependencies exist.
    $files['bin/legion-foundry.ps1'] = Join-Path $binRoot 'legion-foundry.ps1'
    foreach ($relativePath in $files.Keys) {
        $target = Join-Path $runtime $relativePath
        if (-not (Test-LegionOwnerPathSafe $target -StopRoot $HomeRoot)) { throw 'Runtime file contains a link; resolve it before refreshing' }
        $bytes = [IO.File]::ReadAllBytes($files[$relativePath])
        if ((Test-Path -LiteralPath $target) -and [Convert]::ToBase64String([IO.File]::ReadAllBytes($target)) -ceq [Convert]::ToBase64String($bytes)) { continue }
        New-Item -ItemType Directory -Path (Split-Path $target -Parent) -Force | Out-Null
        [IO.File]::WriteAllBytes($target, $bytes)
        if ($null -ne $Changes) { $Changes.Add($target) }
    }
    return Join-Path $runtime 'bin/legion-foundry.ps1'
}

function New-FoundryWrappers {
    param([string]$Id, [string]$HomeRoot, [string]$Tool, [Collections.Generic.List[string]]$Changes)
    Assert-LegionId $Id
    foreach ($suffix in @('', '.cmd')) { Assert-LegionWrapperPath (Get-LegionHomePath -HomeRoot $HomeRoot -Path "bin/$Id$suffix") $Id }
    Add-LegionFootprint -HomeRoot $HomeRoot -Kind folder -Path (Get-LegionOwnerPath -HomeRoot $HomeRoot -Name Runtime) -Owner "account:$Id"
    $runner = Sync-LegionFoundryRuntime -Tool $Tool -HomeRoot $HomeRoot -Changes $Changes
    $bin = Get-LegionHomePath -HomeRoot $HomeRoot -Path 'bin'
    $shPath = ConvertTo-LegionShellLiteral $runner
    $sh = Get-LegionLauncherText -Id $Id -Body ('exec pwsh -NoProfile -File {0} -Agent {1} "$@"' -f $shPath, $Id)
    Write-LegionGeneratedFile -Path (Join-Path $bin $Id) -Content $sh -Changes $Changes -Executable
    $cmd = Get-LegionLauncherText -Id $Id -Windows -Body "@pwsh -NoProfile -File `"$($runner.Replace('%', '%%'))`" -Agent $Id %*"
    Write-LegionGeneratedFile -Path (Join-Path $bin "$Id.cmd") -Content $cmd -Changes $Changes
}

