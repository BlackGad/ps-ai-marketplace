import os
import stat
import sys
import tempfile
from pathlib import Path


def header(name: str, windows: bool) -> str:
    return f"{'@rem' if windows else '#'} Generated by legion: {name}"


def is_owned(path: Path, name: str) -> bool:
    if not path.is_file():
        return False
    try:
        with path.open(encoding="utf-8-sig") as stream:
            first = stream.readline().rstrip("\r\n")
            second = stream.readline().rstrip("\r\n")
    except (OSError, UnicodeError):
        return False
    if path.suffix.lower() == ".cmd":
        return first == header(name, True)
    return first == "#!/bin/sh" and second == header(name, False)


def write_generated(path: Path, text: str, executable: bool) -> bool:
    path = path.resolve()
    same = path.is_file() and path.read_bytes() == text.encode("utf-8")
    if not same:
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
        os.close(fd)
        temp = Path(name)
        try:
            temp.write_text(text, encoding="utf-8", newline="")
            if path.is_file():
                temp.chmod(path.stat().st_mode)
            if executable and sys.platform != "win32":
                temp.chmod(temp.stat().st_mode | stat.S_IXUSR)
            temp.replace(path)
        finally:
            temp.unlink(missing_ok=True)
    changed = not same
    if executable and sys.platform != "win32" and not path.stat().st_mode & stat.S_IXUSR:
        path.chmod(path.stat().st_mode | stat.S_IXUSR)
        changed = True
    return changed


def shell_literal(value: str) -> str:
    return "'" + value.replace("'", "'\"'\"'") + "'"


def cmd_escape(value: str) -> str:
    return value.replace("%", "%%")
